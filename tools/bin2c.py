#!/usr/bin/env python3
"""bin2c: embed a binary file as a C byte array.

usage: bin2c.py <input.bin> <output.c> <symbol>
"""
import sys


def main():
    src, dst, sym = sys.argv[1], sys.argv[2], sys.argv[3]
    with open(src, "rb") as f:
        data = f.read()
    with open(dst, "w") as f:
        f.write(f"/* generated by tools/bin2c.py from {src} — do not edit */\n")
        f.write(f"const unsigned char {sym}[] = {{\n")
        for i in range(0, len(data), 12):
            chunk = data[i:i + 12]
            f.write("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",\n")
        f.write("};\n")
        f.write(f"const unsigned int {sym}_len = {len(data)};\n")
    print(f"{dst}: {len(data)} bytes")


if __name__ == "__main__":
    main()
