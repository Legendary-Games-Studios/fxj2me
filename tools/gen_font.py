#!/usr/bin/env python3
"""fxj2me: generate the 6x8 bitmap font (src/core/font8x8.c) from DejaVu.

Glyph cells are 8x8, bit 7 = leftmost pixel; text advances 6px so 21 chars
fit on the 128px screen. Baseline sits after row 5 (ascent 6, height 8).
Regenerate with: python3 tools/gen_font.py
"""
import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_C = os.path.join(HERE, "..", "src", "core", "font8x8.c")
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"


def glyph(ch):
    img = Image.new("L", (10, 8), 0)
    d = ImageDraw.Draw(img)
    d.text((0, -2), ch, fill=255, font=ImageFont.truetype(FONT, 8))
    px = img.load()
    rows = []
    for y in range(8):
        b = 0
        for x in range(8):
            if px[x, y] >= 100:
                b |= 0x80 >> x
        rows.append(b)
    return rows


def main():
    lines = [
        "/* fxj2me: 6x8 bitmap font (cells 8x8, advance 6), generated by",
        " * tools/gen_font.py from DejaVuSansMono 8px. ASCII 32..126.",
        " * Baseline: glyph row 5 is the last row above it (ascent 6). */",
        '#include "draw.h"',
        "",
        "const uint8_t fx_font8x8[FX_FONT_GLYPHS][8] = {",
    ]
    for c in range(32, 127):
        rows = glyph(chr(c))
        cells = ", ".join(f"0x{b:02x}" for b in rows)
        ch = chr(c)
        label = ch if ch != "\\" else "backslash"
        lines.append(f"    {{ {cells} }},  /* {label} */")
    lines.append("};")
    with open(OUT_C, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.normpath(OUT_C)}")


if __name__ == "__main__":
    main()
